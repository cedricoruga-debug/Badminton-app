-- also drop the *current* names this block itself creates — without this,
-- re-running the script a second time (e.g. this migration, on a database
-- that already had enable_auth_policies.sql applied once) fails with
-- "policy ... already exists" instead of being a no-op like every other
-- policy in this file.
