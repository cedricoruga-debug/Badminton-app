-- Badminton App schema (v2)
-- Mirrors the AppSheet "RFC Sat" app's tables (Sessions, Games, PlayerSessions, Home),
-- rebuilt as a proper relational schema instead of a Google Sheet.
--
-- v2 correction: the real fee model was reverse-engineered from actual historical
-- data (the "Queuing sat" Google Sheet export), which revealed two things v1 got
-- wrong:
--   1. Court/shuttle rates are set PER SESSION (court rental hours x hourly rate,
--      shuttle tube cost split across shuttles and then across a 4-player game),
--      not a single global rate in app_settings.
--   2. "Payable" is not simply CourtShare + ShuttleShare. It's rounded up with a
--      buffer: Payable = ceil((CourtShare + ShuttleShare) / 10) * 10 + 10. This
--      was verified against all 383 historical PlayerSessions rows with zero
--      mismatches, so it's encoded as the generated column formula below.
--   3. "Payment" in the source data is the METHOD used (Cash / Gcash), not a
--      plain paid/unpaid flag.
--
-- Run this in the Supabase SQL editor (or `supabase db push` once you have the CLI set up).

create extension if not exists "pgcrypto";

-- ---------------------------------------------------------------------------
-- players
-- New table (AppSheet stored player names as free text). Having a real table
-- lets us keep a stable roster instead of re-typing names every session.
-- ---------------------------------------------------------------------------
create table if not exists players (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- sessions   (was: AppSheet "Sessions" table)
-- One row per game day. Court/shuttle costs are set here per session (they
-- varied week to week in the historical data — different hours, different
-- rates) and shared out across whoever shows up that day.
-- ---------------------------------------------------------------------------
create table if not exists sessions (
  id uuid primary key default gen_random_uuid(),
  session_date date not null,
  title text,
  status text not null default 'Open' check (status in ('Open', 'Closed')),
  -- 6-digit code players enter on the public /join page to request a spot
  -- in this session — generated by createSession, not by the database, so
  -- it's easy to retry on a collision. Nullable only so old rows (created
  -- before this existed) don't break; every new session gets one.
  join_code text unique,

  hours numeric(5, 2) not null default 0,
  fee_per_hour numeric(10, 2) not null default 0,
  court_fee numeric(10, 2) generated always as (hours * fee_per_hour) stored,

  shuttle_tube_cost numeric(10, 2) not null default 0,
  shuttles_per_tube integer not null default 12,
  cost_per_shuttle numeric(10, 2) generated always as (
    case when shuttles_per_tube = 0 then 0 else shuttle_tube_cost / shuttles_per_tube end
  ) stored,
  -- one shuttle is shared by a 4-player doubles game
  shuttle_fee_per_game numeric(10, 2) generated always as (
    case when shuttles_per_tube = 0 then 0 else shuttle_tube_cost / shuttles_per_tube / 4 end
  ) stored,

  -- how many distinct players showed up this session; court cost is split evenly across them
  player_count integer not null default 0,
  court_share_per_player numeric(10, 2) generated always as (
    case when player_count = 0 then 0 else (hours * fee_per_hour) / player_count end
  ) stored,

  created_at timestamptz not null default now()
);

-- safe to re-run against a database created before join_code existed
alter table sessions add column if not exists join_code text;
alter table sessions drop constraint if exists sessions_join_code_key;
alter table sessions add constraint sessions_join_code_key unique (join_code);

-- ---------------------------------------------------------------------------
-- games   (was: AppSheet "Games" table)
-- One row per individual game (doubles: 4 players) within a session.
-- ---------------------------------------------------------------------------
create table if not exists games (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references sessions(id) on delete cascade,
  game_number integer not null,
  game_date date not null,
  -- 'Requested' = submitted by a player from the public /join page, not yet
  -- approved by the queue master — see "Public game requests" below.
  status text not null default 'Queued' check (status in ('Requested', 'Queued', 'Ongoing', 'Done')),
  player1_id uuid references players(id),
  player2_id uuid references players(id),
  player3_id uuid references players(id),
  player4_id uuid references players(id),
  -- 'team1' = player1+player2, 'team2' = player3+player4, matching the
  -- CourtBox left/right split. Null = no winner recorded (optional — most
  -- games don't need one to keep the queue moving).
  winner_team text check (winner_team is null or winner_team in ('team1', 'team2')),
  score1 integer,
  score2 integer,
  -- Free-text name a player typed in on the public /join "Request a set"
  -- form (see request_game below) — who to credit/ask when the queue master
  -- reviews it. Null for every game logged the normal way (queue master's
  -- own New Game / Edit Game forms never set this).
  requested_by text,
  -- An opaque per-device id (crypto.randomUUID(), generated client-side and
  -- kept in localStorage — see JoinForm.tsx), stored on a "Requested" row
  -- so /join's queue view can show a player only THEIR OWN pending
  -- requests instead of everyone's (get_queue_by_code below scopes on it).
  -- Deliberately not the same thing as requested_by: that's a free-text
  -- name the player may not have bothered typing, this is generated
  -- automatically regardless. Never shown to anyone, including the queue
  -- master — purely a filter key.
  requester_token text,
  created_at timestamptz not null default now(),
  unique (session_id, game_number)
);

-- safe to re-run against a database created before "Ongoing" existed
alter table games drop constraint if exists games_status_check;
alter table games add constraint games_status_check check (status in ('Requested', 'Queued', 'Ongoing', 'Done'));

-- safe to re-run against a database created before requested_by existed
alter table games add column if not exists requested_by text;

-- safe to re-run against a database created before requester_token existed
alter table games add column if not exists requester_token text;

-- safe to re-run against a database created before winner/score existed
alter table games add column if not exists winner_team text;
alter table games drop constraint if exists games_winner_team_check;
alter table games add constraint games_winner_team_check check (winner_team is null or winner_team in ('team1', 'team2'));
alter table games add column if not exists score1 integer;
alter table games add column if not exists score2 integer;

-- ---------------------------------------------------------------------------
-- player_sessions   (was: AppSheet "PlayerSessions" table)
-- One row per player per session: how many games they played and what they owe.
-- court_share is that session's court_share_per_player (constant per player for
-- the day); shuttle_share scales with how many games they actually played.
-- ---------------------------------------------------------------------------
create table if not exists player_sessions (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references sessions(id) on delete cascade,
  player_id uuid not null references players(id),
  total_games integer not null default 0,
  court_share numeric(10, 2) not null default 0,
  shuttle_share numeric(10, 2) not null default 0,
  -- Queue-master-set discount for this player, this session (kids, guests,
  -- whoever brings the shuttles) — a percentage off the court+shuttle cost
  -- before the flat +10 buffer below, not off the final payable amount.
  discount_percent numeric(5, 2) not null default 0 check (discount_percent >= 0 and discount_percent <= 100),
  -- Server-managed (recomputePlayerGameCounts in src/app/actions.ts), not
  -- directly editable: this player's even share of covering everyone
  -- else's discount_percent this session, in pesos, added on top of their
  -- own court+shuttle cost. Always 0 for a player who has a discount of
  -- their own — the cost only spreads across players without one.
  surcharge_amount numeric(10, 2) not null default 0 check (surcharge_amount >= 0),
  payable numeric(10, 2) generated always as (
    case when (court_share + shuttle_share + surcharge_amount) = 0 then 0
         else ceil(((court_share + shuttle_share) * (1 - discount_percent / 100.0) + surcharge_amount) / 10.0) * 10 + 10
    end
  ) stored,
  -- null = unpaid; otherwise the method used
  payment_method text check (payment_method is null or payment_method in ('Cash', 'Gcash')),
  -- set from the "Done" toggle on a player row once someone's finished
  -- playing for the day; excludes them from the New Game player picker
  -- while keeping their games/payment record intact.
  done_for_session boolean not null default false,
  created_at timestamptz not null default now(),
  unique (session_id, player_id)
);

-- safe to re-run against a database created before done_for_session existed
alter table player_sessions add column if not exists done_for_session boolean not null default false;

-- safe to re-run against a database created before discount_percent existed
-- — a generated column's formula can't be altered in place, so this drops
-- and recreates `payable` with the discount folded in. Harmless to re-run:
-- the recomputed value is identical to what's already stored.
alter table player_sessions add column if not exists discount_percent numeric(5, 2) not null default 0
  check (discount_percent >= 0 and discount_percent <= 100);

-- safe to re-run against a database created before surcharge_amount existed
alter table player_sessions add column if not exists surcharge_amount numeric(10, 2) not null default 0;
alter table player_sessions drop constraint if exists player_sessions_surcharge_amount_check;
alter table player_sessions add constraint player_sessions_surcharge_amount_check check (surcharge_amount >= 0);

alter table player_sessions drop column if exists payable;
alter table player_sessions add column payable numeric(10, 2) generated always as (
  case when (court_share + shuttle_share + surcharge_amount) = 0 then 0
       else ceil(((court_share + shuttle_share) * (1 - discount_percent / 100.0) + surcharge_amount) / 10.0) * 10 + 10
  end
) stored;

